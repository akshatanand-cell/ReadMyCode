/**
 * SpecDocGenerator: Generates production-grade README.md, ARCHITECTURE.md,
 * AGENTS.md, and TASK_BREAKDOWN.md directly from codebase files.
 */

function detectProjectDetails(files = [], repoName = "Project") {
  const fileNames = files.map((f) => (f.path || "").toLowerCase());
  const extensions = new Set(files.map((f) => (f.extension || "").toLowerCase()));

  const hasPython = extensions.has(".py");
  const hasJS = extensions.has(".js") || extensions.has(".jsx") || extensions.has(".ts") || extensions.has(".tsx");
  const hasJava = extensions.has(".java");
  const hasCpp = extensions.has(".cpp") || extensions.has(".c") || extensions.has(".h") || extensions.has(".hpp");
  const hasGo = extensions.has(".go");

  let projectType = "general";
  let isStreamlit = false;
  let entryPoint = "";

  if (hasPython) {
    projectType = "python";
    const streamlitCandidate = files.find(
      (f) =>
        f.content?.includes("import streamlit") ||
        f.content?.includes("from streamlit") ||
        f.path?.toLowerCase().includes("streamlit")
    );
    if (streamlitCandidate) {
      isStreamlit = true;
      entryPoint = streamlitCandidate.path;
    } else {
      const pyEntry = files.find(
        (f) =>
          f.path.toLowerCase() === "app.py" ||
          f.path.toLowerCase() === "main.py" ||
          f.path.toLowerCase().endsWith("/app.py") ||
          f.path.toLowerCase().endsWith("/main.py")
      );
      entryPoint = pyEntry ? pyEntry.path : files.find((f) => f.extension === ".py")?.path || "main.py";
    }
  } else if (hasJS) {
    projectType = "node";
    const jsEntry = files.find(
      (f) =>
        f.path.toLowerCase() === "server.js" ||
        f.path.toLowerCase() === "index.js" ||
        f.path.toLowerCase() === "app.js" ||
        f.path.toLowerCase().includes("src/index") ||
        f.path.toLowerCase().includes("src/main")
    );
    entryPoint = jsEntry ? jsEntry.path : "index.js";
  } else if (hasJava) {
    projectType = "java";
    entryPoint = files.find((f) => f.extension === ".java")?.path || "Main.java";
  } else if (hasCpp) {
    projectType = "cpp";
    entryPoint = files.find((f) => f.extension === ".cpp" || f.extension === ".c")?.path || "main.cpp";
  }

  // Extract dependencies
  const dependencies = [];
  const reqTxt = files.find((f) => f.path.toLowerCase() === "requirements.txt");
  if (reqTxt && reqTxt.content) {
    reqTxt.content.split("\n").forEach((line) => {
      const clean = line.trim().split("=")[0].split(">")[0].split("<")[0].trim();
      if (clean && !clean.startsWith("#")) dependencies.push(clean);
    });
  }

  const pkgJson = files.find((f) => f.path.toLowerCase() === "package.json");
  if (pkgJson && pkgJson.content) {
    try {
      const parsed = JSON.parse(pkgJson.content);
      const allDeps = { ...(parsed.dependencies || {}), ...(parsed.devDependencies || {}) };
      dependencies.push(...Object.keys(allDeps));
    } catch {}
  }

  return {
    projectType,
    isStreamlit,
    entryPoint: entryPoint || (files[0] ? files[0].path : "index.js"),
    dependencies: dependencies.slice(0, 15),
    fileCount: files.length,
    languages: Array.from(extensions)
      .map((e) => e.replace(".", "").toUpperCase())
      .filter((e) => e.length > 0 && e.length < 8),
  };
}

function generateReadmeDoc({ repoName, files = [], tree = "" }) {
  const details = detectProjectDetails(files, repoName);
  const codeFiles = files.filter((f) => f.path && !f.path.startsWith("."));
  const primaryFiles = codeFiles.slice(0, 8).map((f) => `- \`${f.path}\``).join("\n");

  const runCommand =
    details.projectType === "python"
      ? details.isStreamlit
        ? `streamlit run ${details.entryPoint}`
        : `python ${details.entryPoint}`
      : details.projectType === "node"
      ? `npm install\nnpm start`
      : details.projectType === "cpp"
      ? `g++ -O3 ${details.entryPoint} -o app\n./app`
      : `java ${details.entryPoint}`;

  const installCommand =
    details.projectType === "python"
      ? `python -m venv venv\nsource venv/bin/activate  # On Windows: venv\\Scripts\\activate\npip install -r requirements.txt`
      : details.projectType === "node"
      ? `npm install`
      : `# Install language dependencies as needed`;

  return `# ${repoName}

> Automated codebase and system documentation generated by **ReadMyCode**.

---

## 📌 Project Overview
**${repoName}** is a ${details.projectType} application containing ${details.fileCount} source files. It is structured with modular design, optimized algorithms, and designated entry points for execution.

- **Primary Stack**: ${details.languages.join(", ") || "General Software"}
- **Primary Entry Point**: \`${details.entryPoint}\`
${details.isStreamlit ? "- **Framework**: Streamlit Interactive Data Application" : ""}
${details.dependencies.length > 0 ? `- **Core Dependencies**: ${details.dependencies.join(", ")}` : ""}

---

## 🚀 Getting Started

### 1. Prerequisites
Ensure you have the required runtime environment installed:
${
  details.projectType === "python"
    ? "- Python 3.9+ and `pip`"
    : details.projectType === "node"
    ? "- Node.js 18+ and `npm`"
    : "- Compatible C++/Java/compiler toolchain"
}

### 2. Installation
\`\`\`bash
${installCommand}
\`\`\`

### 3. Run the Application
\`\`\`bash
${runCommand}
\`\`\`

---

## 📂 Key Source Files
${primaryFiles || "- No source files detected"}

---

## 🛠 Project Structure
\`\`\`text
${(tree || "").slice(0, 1500) || "Project root"}
\`\`\`

---

## 🤝 Contributing & License
Maintained by ${repoName} Contributors. Open for improvements and pull requests.
`;
}

function generateArchitectureMermaid({ repoName, files = [] }) {
  const details = detectProjectDetails(files, repoName);
  if (details.projectType === "python") {
    return `flowchart TD
    Client["Client / Execution Environment"] --> Entry["${details.entryPoint} (Core Entry Point)"]
    Entry --> Modules["Computational & Business Modules"]
    Modules --> DataLayer["Data & State Storage"]
    Modules --> Output["Execution Results & UI"]`;
  }
  return `flowchart LR
  UI["User Interface Layer"] --> Gateway["API & Routing Gateway"]
  Gateway --> Controllers["Business Logic Controllers"]
  Controllers --> Services["Utility & Model Layer"]
  Services --> DB["Database / Persistence Layer"]`;
}

function generateArchitectureDoc({ repoName, files = [] }) {
  const details = detectProjectDetails(files, repoName);
  const mermaidDiagram = generateArchitectureMermaid({ repoName, files });

  return `# ${repoName} — Architecture Documentation

## System Topology & Flowchart

\`\`\`mermaid
${mermaidDiagram}
\`\`\`

---

## Architecture Overview
The system is organized into modular layers ensuring separation of concerns:

1. **Entry Layer**: Handled through \`${details.entryPoint}\`, responsible for bootstrap, argument parsing, or request routing.
2. **Logic & Processing Layer**: Encapsulates core business algorithms, data transformations, and system pipelines.
3. **Data Layer**: Persists state, schemas, and operational records.
4. **Interface / Client Layer**: Exposes user interactions, HTTP REST endpoints, or CLI commands.

---

## Technology Stack Breakdown
- **Runtime**: ${details.projectType.toUpperCase()}
- **Languages**: ${details.languages.join(", ")}
- **Modules Parsed**: ${details.fileCount} source files
`;
}

function generateAgentsDoc({ repoName, files = [] }) {
  const details = detectProjectDetails(files, repoName);

  return `# ${repoName} — Agent Rules & Mission Control Constitution

## Purpose
This document defines operational guidelines, coding standards, and safety boundaries for autonomous AI coding agents collaborating on **${repoName}**.

---

## 1. Core Principles
1. **Spec-Driven Execution**: No code without verified specifications and tasks.
2. **Preserve Existing Architecture**: Respect project patterns and avoid breaking existing interfaces.
3. **Clean Code**: Use descriptive function names, concise error handling, and language-standard conventions (${details.projectType === "python" ? "PEP 8" : "ESLint/Prettier"}).
4. **Empirical Validation**: Validate all changes with unit tests or local execution before committing.

---

## 2. Language-Specific Standards
${
  details.projectType === "python"
    ? `- Always use type hints in function signatures (\`def process(data: dict) -> bool:\`).
- Handle exceptions with structured \`try/except\` blocks with clear error logs.
- Keep dependencies updated in \`requirements.txt\`.
- Use \`${details.entryPoint}\` as the canonical reference entry point.`
    : `- All asynchronous operations MUST use \`async/await\`.
- Strictly avoid \`var\`; prefer \`const\` and scoped \`let\`.
- Validate user input before processing.
- Maintain consistent JSON responses: \`{ data, message, error }\`.`
}

---

## 3. Deployment & CI/CD
- Main branch must always remain buildable and error-free.
- Target deployment platform: **${details.isStreamlit ? "Streamlit Cloud" : details.projectType === "python" ? "Streamlit / Python Container" : "Vercel / Cloud Platform"}**.
`;
}

