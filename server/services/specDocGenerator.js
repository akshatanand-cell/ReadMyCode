function generateFlowchartMermaid({ repoName, files = [] }) {
  const details = detectProjectDetails(files, repoName);
  if (details.projectType === "python") {
    return `flowchart TD
    Start["Initiate Application"] --> Load["Load Environment & Config"]
    Load --> Run["Execute ${details.entryPoint.replace(/[^a-zA-Z0-9._-]/g, "")}"]
    Run --> Process["Process Input & Algorithms"]
    Process --> Output["Generate Output & Visualizations"]`;
  }
  return `flowchart TD
  User["User / Client Request"] --> Router["API Router & Middleware"]
  Router --> Handler["Core Service Handler"]
  Handler --> Database["Database & State Store"]
  Database --> Response["JSON Response / View Render"]`;
}

